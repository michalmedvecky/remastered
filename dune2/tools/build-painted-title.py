"""Trace the actual 1992 Dune II logo independently of the new UI typeface."""
from pathlib import Path
import argparse,base64,hashlib,importlib.util,json
ROOT=Path(__file__).resolve().parents[1]
spec=importlib.util.spec_from_file_location('period_contours',ROOT/'tools/build-painted-typography.py')
period=importlib.util.module_from_spec(spec);spec.loader.exec_module(period)
def build():
 scene=json.loads((ROOT/'dist/painted/interface.json').read_text())['scenes']['TITLE.ENG']
 pixels=base64.b64decode(scene['indicesBase64']);x,y,w,h=53,60,216,39
 cells={(px,py)for py in range(h)for px in range(w)if pixels[(y+py)*320+x+px]}
 result={'schema':1,'source':'TITLE.ENG','sourceIndicesSHA256':hashlib.sha256(pixels).hexdigest(),'nativeRect':[x,y,w,h],'foregroundPixels':len(cells),'contours':period.contours(cells)}
 return '// Generated by tools/build-painted-title.py; original Dune II logo outline.\nexport default '+json.dumps(result,separators=(',',':'))+';\n'
def main():
 parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--check',action='store_true');args=parser.parse_args()
 path=ROOT/'dist/painted-title-data.mjs';result=build()
 if args.check:
  if not path.is_file()or path.read_text()!=result:raise SystemExit('Title outline is not reproducible')
 else:path.write_text(result)
 print(json.dumps({'output':str(path),'verified':args.check}))
if __name__=='__main__':main()
