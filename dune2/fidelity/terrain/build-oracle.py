'''
    landscape_type=function(texts['map'],'Map_GetLandscapeType').replace('t = &g_map[packed];','if (packed >= 4096) return LST_ENTIRELY_ROCK; /* Explicit cleared-neighbor model. */\n\tt = &g_map[packed];')
    edges=function(texts['map'],'Map_FixupSpiceEdges').replace('if (Tile_IsOutOfMap(curPacked)) {','if (false) { /* Native check masks coordinates before comparing; unreachable. */')
    source=prefix+initializer(tile,'_stepX[256]')+initializer(tile,'_stepY[256]')+function(texts['tools'],'Tools_Random_Seed')+random+function(tile,'Tile_UnpackTile')+native_distance+'\n#ifdef NATIVE_SAR\n'+native_move+'\n#else\n'+move+'\n#endif\n'+function(texts['map'],'Map_AddSpiceOnTile')+initializer(texts['map'],'_offsetTable[2][21][4]')+algorithm+initializer(texts['map'],'_landscapeSpriteMap[81]')+landscape_type+edges+function(texts['map'],'Map_ChangeSpiceAmount')+function(texts['map'],'Map_FillCircleWithSpice')
    source+='''
