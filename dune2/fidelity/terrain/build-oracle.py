"""Build a bounded portable C landscape oracle, never run DOS code.

The C algorithm is retained from pinned GPL-2.0 OpenDUNE source; the native SAR
rounding correction is verified against supplied V1.07 instruction bytes. The
oracle runs only the pure generator in a cleared host array and writes fixtures.
"""
